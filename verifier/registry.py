"""Registry layout and merge rules.

  registry/attempts/<template>/<key>.json   one record per (template, repo, commit); key = owner_repo@commit
  registry/<template>.json                  summary record: the best attempt (clean match > match > miss,
                                            then newer verifier pipeline, then newest), plus an `attempts` list
  registry/SUMMARY.md                       regenerated by summary.py

Merge rules (apply): a new attempt replaces an existing one for the same key only if it matches, or the
existing one does not match, or the existing one was recorded by an older verifier pipeline (a hardened
re-run of the same input is the honest answer). A miss never replaces a match from the same pipeline, and a
miss for one (repo, commit) never hides a match for another: the summary always shows the best attempt.

Usage: python -I verifier/registry.py apply <new_dir> <registry_dir>
       python -I verifier/registry.py rebuild <registry_dir>
"""
import glob, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)


def key(repo, commit):
    r = re.sub(r"(\.git)?/*$", "", str(repo or "").strip()).lower()
    r = re.sub(r"^https?://(www\.)?github\.com/", "", r)
    r = re.sub(r"[^a-z0-9._-]+", "_", r).strip("_")[:80] or "repo"
    c = re.sub(r"[^0-9a-f]", "", str(commit or "").lower())[:40] or "unknown"
    return f"{r}@{c}"


def rank(r):
    return (bool(r.get("match")), bool(r.get("clean")), int(r.get("pipeline") or 1), r.get("verified_at") or "")


def seed(reg, hx):
    """Turn a pre-attempts registry/<hx>.json into its first attempt (pipeline 1)."""
    d = os.path.join(reg, "attempts", hx)
    top = os.path.join(reg, hx + ".json")
    if os.path.isdir(d) or not os.path.exists(top):
        return
    r = json.load(open(top))
    if "template" not in r:
        return
    r.pop("attempts", None)
    r.setdefault("pipeline", 1)
    k = key(r.get("repo"), r.get("commit"))
    r["attempt_key"] = k
    os.makedirs(d, exist_ok=True)
    json.dump(r, open(os.path.join(d, k + ".json"), "w"), indent=2)


def summarize(reg, hx):
    recs = []
    for p in sorted(glob.glob(os.path.join(reg, "attempts", hx, "*.json"))):
        recs.append(json.load(open(p)))
    if not recs:
        return
    recs.sort(key=rank, reverse=True)
    best = dict(recs[0])
    if int(best.get("pipeline") or 1) < 2:
        best["warnings"] = list(best.get("warnings") or []) + [
            "recorded by an earlier verifier (before the record job stopped trusting build artifacts)"]
        best["clean"] = False
    best["attempts"] = [{"key": r.get("attempt_key"), "repo": r.get("repo"), "commit": r.get("commit"),
                         "match": r.get("match"), "clean": r.get("clean"), "mode": r.get("mode"),
                         "pipeline": r.get("pipeline") or 1, "run_url": r.get("run_url"),
                         "verified_at": r.get("verified_at")} for r in recs]
    json.dump(best, open(os.path.join(reg, hx + ".json"), "w"), indent=2)


def apply(new_dir, reg):
    touched = set()
    for p in sorted(glob.glob(os.path.join(new_dir, "attempts", "*", "*.json"))):
        hx = os.path.basename(os.path.dirname(p))
        if not re.fullmatch(r"[0-9a-f]{64}", hx):
            continue
        new = json.load(open(p))
        if new.get("template") != hx:
            continue
        seed(reg, hx)
        k = key(new.get("repo"), new.get("commit"))
        new["attempt_key"] = k
        dest = os.path.join(reg, "attempts", hx, k + ".json")
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        if os.path.exists(dest):
            old = json.load(open(dest))
            keep_old = old.get("match") and not new.get("match") \
                and int(old.get("pipeline") or 1) >= int(new.get("pipeline") or 1)
            if keep_old:
                print(f"{hx[:12]} {k}: kept the existing match; the new miss ({new.get('run_url')}) is not recorded over it")
                continue
        json.dump(new, open(dest, "w"), indent=2)
        touched.add(hx)
    for hx in touched:
        summarize(reg, hx)
    import summary
    summary.write(reg)
    return touched


def rebuild(reg):
    for p in glob.glob(os.path.join(reg, "*.json")):
        hx = os.path.basename(p)[:-5]
        if re.fullmatch(r"[0-9a-f]{64}", hx):
            seed(reg, hx)
            summarize(reg, hx)
    import summary
    summary.write(reg)


if __name__ == "__main__":
    if sys.argv[1] == "apply":
        apply(sys.argv[2], sys.argv[3])
    elif sys.argv[1] == "rebuild":
        rebuild(sys.argv[2])
