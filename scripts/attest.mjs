#!/usr/bin/env node
// OneScan attestation path: turn registry/<hex>.json results with match=true into SourceRegistry
// `attest` calls, as a transaction manifest for the wallet UI's Manifest page, or (optionally)
// submitted to a LOCAL tari_ootle_walletd over JSON-RPC.
//
// Nothing is submitted unless you pass both --rpc and --submit. Nothing here reads or prints secrets.
//
// Commands:
//   node scripts/attest.mjs create <template_hex|template_...>          manifest: instantiate SourceRegistry
//   node scripts/attest.mjs attest [--registry component_...] [--only <hex>,<hex>] [--out file.rs]
//                                                                        manifest: one tx, one attest() per match
//   add --rpc to send the manifest to walletd as a dry run (fee estimate); add --rpc --submit to submit it.
//
// Env (only for --rpc, same as ootle-split/scripts/walletd.mjs):
//   WALLETD_URL (default http://127.0.0.1:5100/json_rpc), WALLETD_TOKEN or WALLETD_COOKIE,
//   FEE_ACCOUNT (component_... or account name; default: the wallet's default account), MAX_FEE (microTARI).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const argv = process.argv.slice(2)
const flag = (n) => argv.includes(n)
const opt = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : undefined }
const positional = argv.filter((a, i) => !a.startsWith('--') && !(i > 0 && ['--registry', '--only', '--out'].includes(argv[i - 1])))
const [cmd, ...rest] = positional
const RPC = flag('--rpc')
const SUBMIT = flag('--submit')
const MAX = (d) => Number(process.env.MAX_FEE ?? d)

const isHex = (s, n) => typeof s === 'string' && new RegExp(`^[0-9a-f]{${n}}$`).test(s)
const isComponent = (s) => /^component_[0-9a-f]{64}$/.test(s ?? '')
const hex = (t) => String(t).replace(/^template_/, '')
const printable = (s, max) => String(s).replace(/[^\x20-\x7e]/g, ' ').slice(0, max).trim()

// Mirrors the template's validation (registry-template/src/lib.rs) so a bad row never reaches the chain.
function toAttestation(r) {
  const why = []
  const a = {
    template: `template_${r.template}`,
    source_sha256: r.built_sha256,
    onchain_sha256: r.onchain_sha256,
    repo: r.repo,
    commit: r.commit,
    mode: r.mode,
    toolchain: printable([r.toolchain?.rustc, r.toolchain?.tari_cli].filter(Boolean).join(' / '), 64),
    run_url: r.run_url,
  }
  if (!isHex(r.template, 64)) why.push('template')
  if (!isHex(a.source_sha256, 64) || a.source_sha256 !== a.onchain_sha256) why.push('hash')
  if (!/^https:\/\/[\x21-\x7e]{1,192}$/.test(a.repo ?? '')) why.push('repo')
  if (!/^[0-9a-f]{7,64}$/.test(a.commit ?? '')) why.push('commit')
  if (!['raw', 'walletd-optimized'].includes(a.mode)) why.push('mode')
  if (!a.toolchain) why.push('toolchain')
  if (!/^https:\/\/[\x21-\x7e]{1,192}$/.test(a.run_url ?? '')) why.push('run_url')
  return { a, why }
}

function matches() {
  const only = opt('--only')?.split(',').map(hex)
  const dir = join(ROOT, 'registry')
  const rows = []
  for (const f of readdirSync(dir).filter((f) => /^[0-9a-f]{64}\.json$/.test(f)).sort()) {
    const r = JSON.parse(readFileSync(join(dir, f), 'utf8'))
    if (r.match !== true) continue
    if (only && !only.includes(r.template)) continue
    const { a, why } = toAttestation(r)
    if (why.length) { console.error(`skip ${r.name ?? r.template}: invalid ${why.join(', ')}`); continue }
    rows.push({ name: r.name, a })
  }
  return rows
}

const s = (v) => JSON.stringify(v)
const FEE_BLOCK = (fee) => `fn fee_main() {
    let account = var!["account"];
    account.pay_fee(${fee});
}`

function createManifest(tpl) {
  if (!isHex(hex(tpl), 64)) throw new Error('usage: create <template_hex|template_...>')
  return `// OneScan: instantiate the SourceRegistry component (no owner, anyone may attest).
// Manifest page variable: account = your component_... (pays the fee)
use template_${hex(tpl)} as SourceRegistry;

${FEE_BLOCK(MAX(100_000))}

fn main() {
    SourceRegistry::new();
}
`
}

function attestManifest(rows, registry) {
  const fee = MAX(100_000 + 25_000 * rows.length)
  const calls = rows.map(({ name, a }) => `    // ${printable(name ?? '', 60)}
    registry.attest(${s(a.template)}, ${s(a.source_sha256)}, ${s(a.onchain_sha256)}, ${s(a.repo)}, ${s(a.commit)}, ${s(a.mode)}, ${s(a.toolchain)}, ${s(a.run_url)});`)
  return `// OneScan: ${rows.length} source attestation(s), one transaction. Generated by scripts/attest.mjs from registry/*.json (match=true).
// Manifest page variables: account = your component_... (pays the fee), registry = ${registry ?? 'the SourceRegistry component_...'}
${FEE_BLOCK(fee)}

fn main() {
    let registry = var!["registry"];
${calls.join('\n')}
}
`
}

// ---- optional walletd JSON-RPC (pattern from ootle-split/scripts/walletd.mjs) ----
const URL_ = process.env.WALLETD_URL ?? 'http://127.0.0.1:5100/json_rpc'
let id = 0
let token = process.env.WALLETD_TOKEN ?? (process.env.WALLETD_COOKIE ? readFileSync(process.env.WALLETD_COOKIE, 'utf8').trim() : null)
async function raw(method, params) {
  const r = await fetch(URL_, {
    method: 'POST',
    headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) },
    body: JSON.stringify({ jsonrpc: '2.0', id: ++id, method, params }),
  })
  return r.json()
}
async function call(method, params = {}) {
  if (!token) {
    const a = await raw('auth.request', { credentials: 'None', permissions: ['Admin'] })
    if (a.error) throw new Error(`auth failed (${JSON.stringify(a.error)}). Set WALLETD_TOKEN or WALLETD_COOKIE.`)
    token = a.result.token
  }
  const j = await raw(method, params)
  if (j.error) throw new Error(`${method}: ${JSON.stringify(j.error).slice(0, 1200)}`)
  return j.result
}
async function feeAccount() {
  if (process.env.FEE_ACCOUNT) return process.env.FEE_ACCOUNT
  const d = await call('accounts.get_default', {})
  const addr = JSON.stringify(d).match(/component_[0-9a-f]{64}/)
  if (!addr) throw new Error('could not find the default account; set FEE_ACCOUNT=component_...')
  return addr[0]
}
async function submitManifest(code, variables, maxFee) {
  const info = await call('wallet.get_info', {})
  const net = JSON.stringify(info).match(/"network"\s*:\s*"([^"]+)"/)?.[1] ?? 'unknown'
  console.error(`wallet daemon network: ${net}${SUBMIT ? '  (SUBMITTING)' : '  (dry run)'}`)
  const res = await call('transactions.submit_manifest', {
    manifest: code, variables, seal_signer_key_id: null, signing_key_ids: [], max_fee: maxFee, dry_run: !SUBMIT, blobs: {},
  })
  console.log(JSON.stringify(res, null, 2))
  if (SUBMIT && res.transaction_id) {
    const r = await call('transactions.wait_result', { transaction_id: res.transaction_id, timeout_secs: 180 })
    console.error(`status: ${r.status ?? 'unknown'}`)
    console.error(`explorer: https://explorer.tari.mw/tx/${res.transaction_id}`)
  }
}

let code, vars = {}, maxFee
if (cmd === 'create') {
  code = createManifest(rest[0])
  maxFee = MAX(100_000)
} else if (cmd === 'attest') {
  const registry = opt('--registry')
  if (registry && !isComponent(registry)) throw new Error('--registry must be component_<64 hex>')
  const rows = matches()
  if (!rows.length) throw new Error('no match=true results in registry/')
  console.error(`${rows.length} attestation(s): ${rows.map((r) => r.name).join(', ')}`)
  code = attestManifest(rows, registry)
  maxFee = MAX(100_000 + 25_000 * rows.length)
  if (registry) vars.registry = registry
} else {
  console.log(readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 16).join('\n'))
  process.exit(cmd ? 1 : 0)
}

const outFile = opt('--out')
if (outFile) { writeFileSync(outFile, code); console.error(`wrote ${outFile}`) } else if (!RPC) process.stdout.write(code)

if (RPC) {
  if (cmd === 'attest' && !vars.registry) throw new Error('--rpc needs --registry component_...')
  vars.account = await feeAccount()
  await submitManifest(code, vars, maxFee)
} else if (SUBMIT) {
  console.error('--submit does nothing without --rpc (manifest only; paste it into the Manifest page).')
}
